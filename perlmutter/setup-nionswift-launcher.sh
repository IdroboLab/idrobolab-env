#!/bin/bash
# setup-nionswift-launcher.sh — one-shot setup of the Nion Swift one-click
# ThinLinc desktop launcher described in nionswift-perlmutter-thinlinc.md §5.1/§5.2.
#
# It detects which machine it is on:
#   1. on a Perlmutter login node (MAINTAINER, once): installs the shared job
#      script, desktop entry, and icon into the project directories (§5.1);
#   2. on a ThinLinc host (EACH group member, once): sets up ssh auth, copies
#      the desktop entry + icon from the shared location into the ThinLinc
#      home, and links the entry onto ~/Desktop (§5.2).
#
# Idempotent — safe to re-run after changing the knobs below (or the
# NIONSWIFT_* environment variables of the same names).
set -euo pipefail

ACCOUNT="${NIONSWIFT_ACCOUNT:-<project>}"
ENV="${NIONSWIFT_ENV:-/global/common/software/${ACCOUNT}/venvs/nionswift-py313}"
SALLOC_OPTS="${NIONSWIFT_SALLOC_OPTS:--q shared_interactive -C cpu -n 1 -c 32 --mem=120G -t 04:00:00}"

# Shared install locations (Perlmutter side; user-independent contents).
BIN_DIR="/global/common/software/${ACCOUNT}/bin"
SHARE_DIR="/global/common/software/${ACCOUNT}/share/nionswift"
JOB="$BIN_DIR/nionswift-job.sh"
DESKTOP_SRC="$SHARE_DIR/nionswift-perlmutter.desktop"
ICON_SRC="$SHARE_DIR/nionswift.png"

# ThinLinc-side per-user install locations.
DESKTOP_REL=".local/share/applications/nionswift-perlmutter.desktop"
ICON_REL=".local/share/icons/hicolor/256x256/apps/nionswift.png"

install_ssh_config() {
    if ! grep -qs 'IdentityFile ~/.ssh/nersc' ~/.ssh/config; then
        mkdir -p ~/.ssh && chmod 700 ~/.ssh
        printf '\nHost perlmutter perlmutter.nersc.gov\n    IdentityFile ~/.ssh/nersc\n' >> ~/.ssh/config
        chmod 600 ~/.ssh/config
    fi
}

if command -v salloc >/dev/null 2>&1 && [ -d /global/common/software ]; then
    ##################### Perlmutter side (maintainer) ######################
    if [ ! -x "$ENV/bin/nionswift" ]; then
        echo "error: $ENV/bin/nionswift not found or not executable" >&2
        echo "       set NIONSWIFT_ENV to the env prefix (runbook §4)" >&2
        exit 1
    fi

    # group-usability check: a venv whose interpreter resolves into a home
    # directory is unusable by other project members (runbook §4)
    PYREAL="$(readlink -f "$ENV/bin/python" 2>/dev/null || true)"
    case "$PYREAL" in
        /global/homes/*|/home/*)
            echo "warning: $ENV/bin/python resolves to" >&2
            echo "         $PYREAL" >&2
            echo "         (inside a home directory — group members cannot use this env;" >&2
            echo "         reinstall the interpreter with UV_PYTHON_INSTALL_DIR set, §4)" >&2
            ;;
    esac

    mkdir -p "$BIN_DIR" "$SHARE_DIR"

    # Extract the Nion Swift logo from the launcher's bundled Windows icon
    # (the PyPI/conda linux builds ship without it — then fetch it from the
    # nionswift-tool repo). Falls back to a stock icon name.
    ICON_NAME=utilities-system-monitor
    ICO="$ENV/bin/NionSwiftLauncher/Graphics/WinIcon.ico"
    if [ ! -f "$ICO" ]; then
        ICO="$HOME/.cache/nionswift-WinIcon.ico"
        mkdir -p ~/.cache
        curl -fsSL -o "$ICO" \
            https://raw.githubusercontent.com/nion-software/nionswift-tool/master/launcher/Graphics/WinIcon.ico \
            || ICO=""
    fi
    if [ -n "$ICO" ] && [ -f "$ICO" ]; then
        if "$ENV/bin/python" - "$ICO" "$ICON_SRC" <<'PYEOF'
import sys
from PIL import Image
im = Image.open(sys.argv[1])
if im.size != (256, 256):
    im = im.resize((256, 256), Image.LANCZOS)
im.save(sys.argv[2])
PYEOF
        then
            ICON_NAME=nionswift
        else
            echo "note: icon conversion failed - using a stock icon" >&2
        fi
    else
        echo "note: no icon in the env and download failed - using a stock icon" >&2
    fi

    # conda/module envs need the §7.6 libexpat preload (dynamic pyexpat);
    # uv-managed venvs do not (pyexpat is compiled into the interpreter)
    # and have no lib/libexpat.so.1 to point at.
    PRELOAD=""
    if [ -f "$ENV/lib/libexpat.so.1" ]; then
        PRELOAD="LD_PRELOAD=$ENV/lib/libexpat.so.1 "
    fi

    cat > "$JOB" <<EOF
#!/bin/bash
# Generated by setup-nionswift-launcher.sh (hpcenvs perlmutter runbook §5.1).
# Allocate a slice and run Nion Swift on the compute node, X forwarded back
# through this login node. Closing Swift releases the allocation.
exec salloc -A ${ACCOUNT} ${SALLOC_OPTS} -J nionswift \\
     bash -c "ssh -X \\"\\\$SLURM_NODELIST\\" '${PRELOAD}${ENV}/bin/nionswift'"
EOF
    chmod 755 "$JOB"

    cat > "$DESKTOP_SRC" <<EOF
[Desktop Entry]
Type=Application
Name=Nion Swift (Perlmutter)
Comment=Allocate a compute-node slice and launch Nion Swift
Exec=ssh -X perlmutter.nersc.gov $JOB
Icon=$ICON_NAME
Terminal=true
Categories=Science;Education;
EOF
    chmod 644 "$DESKTOP_SRC"
    chmod -R g+rX "$SHARE_DIR"

    SELF="$(readlink -f "$0")"
    echo "Shared install done (account: $ACCOUNT, env: $ENV):"
    echo "  $JOB"
    echo "  $DESKTOP_SRC"
    [ "$ICON_NAME" = nionswift ] && echo "  $ICON_SRC"
    echo
    echo "Next: EACH group member, in a terminal INSIDE the ThinLinc desktop:"
    echo "  scp perlmutter.nersc.gov:$SELF ~"
    echo "  ~/$(basename "$SELF")"
    echo "(runbook §5.2)"
else
    ################## ThinLinc side (each group member) ####################
    echo "No Slurm here — assuming ThinLinc host; installing the desktop entry."

    install_ssh_config
    if [ ! -f ~/.ssh/nersc ]; then
        echo "note: no sshproxy key (~/.ssh/nersc) on this host." >&2
        echo "      Run: sshproxy -u $USER   (needed for passwordless launch;" >&2
        echo "      the key expires after 24 h). Continuing — scp may prompt." >&2
    fi

    # icon (non-fatal — a stock icon shows if it is missing)
    mkdir -p "$(dirname ~/"$ICON_REL")"
    scp "perlmutter.nersc.gov:$ICON_SRC" ~/"$ICON_REL" \
        || echo "note: no shared icon at $ICON_SRC - a stock icon will show" >&2

    mkdir -p ~/.local/share/applications ~/Desktop
    if ! scp "perlmutter.nersc.gov:$DESKTOP_SRC" ~/"$DESKTOP_REL"; then
        echo "error: could not fetch the desktop entry from Perlmutter." >&2
        echo "       The maintainer must run this script on a Perlmutter login" >&2
        echo "       node first (§5.1), and 'ssh perlmutter.nersc.gov true'" >&2
        echo "       must work from here (§5.2)." >&2
        exit 1
    fi
    # scp does not preserve the exec bit, and MATE shows a non-executable
    # launcher as an untrusted text file
    chmod +x ~/"$DESKTOP_REL"

    # rewrite Icon= to an absolute local path: name-based icon lookup is
    # unreliable on the ThinLinc hosts' older MATE/GTK, absolute paths
    # always resolve
    if [ -f ~/"$ICON_REL" ]; then
        sed -i "s|^Icon=nionswift$|Icon=$HOME/$ICON_REL|" ~/"$DESKTOP_REL"
    fi
    ln -sf ~/"$DESKTOP_REL" ~/Desktop/nionswift-perlmutter.desktop

    command -v update-desktop-database >/dev/null 2>&1 && \
        update-desktop-database ~/.local/share/applications || true

    echo "ThinLinc side installed:"
    echo "  ~/$DESKTOP_REL (+ ~/Desktop link)"
    echo
    echo "No relogin needed — the menu picks the entry up on next open, and"
    echo "the Desktop icon is immediate (MATE may ask to mark it trusted on"
    echo "first launch). Launch by menu, Desktop icon, or a run dialog:"
    echo "  gtk-launch nionswift-perlmutter        (runbook §5.3)"
fi
